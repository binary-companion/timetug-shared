//! Text helpers shared by the rules: Swift's `lowercased()`, Foundation's folding and case-insensitive comparison, and
//! user-perceived characters (Swift's `Character`).

use crate::fold_table::{CASEFOLD, DECOMP, EXTEND, MARKS};

/// Swift's `String.lowercased()`: every scalar is lowercased on its own. Rust's `str::to_lowercase` also applies the
/// final-sigma rule (`ΟΔΥΣΣΕΥΣ` ends in `ς`); Swift does not (`οδυσσευσ`), and `vectors/text/dedup-key.json` pins that.
pub(crate) fn lowercased(text: &str) -> String {
    text.chars().flat_map(char::to_lowercase).collect()
}

fn in_ranges(table: &[(char, char)], c: char) -> bool {
    table
        .binary_search_by(|&(low, high)| {
            if c < low {
                std::cmp::Ordering::Greater
            } else if c > high {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

fn lookup(table: &'static [(char, &'static str)], c: char) -> Option<&'static str> {
    table
        .binary_search_by_key(&c, |&(key, _)| key)
        .ok()
        .map(|index| table[index].1)
}

/// Appends the folding of one character that is already decomposed: marks vanish, letters are case folded.
fn push_folded(c: char, out: &mut String) {
    if c.is_ascii() {
        out.push(c.to_ascii_lowercase());
    } else if in_ranges(MARKS, c) {
        // diacritic insensitive: a nonspacing mark is dropped
    } else if let Some(folding) = lookup(CASEFOLD, c) {
        out.extend(folding.chars().filter(|f| !in_ranges(MARKS, *f)));
    } else {
        out.push(c);
    }
}

/// `folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil)`: canonical decomposition, nonspacing marks
/// dropped, full case folding (`ß` becomes `ss`, `ς` becomes `σ`). Width is not folded (`Ａ` stays `ａ`). The data is
/// generated by `scripts/dev/generate-fold-table.py` and checked against `vectors/text/fold.json`. Hangul syllables are
/// left composed.
pub fn fold(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if c.is_ascii() {
            out.push(c.to_ascii_lowercase());
        } else if let Some(decomposed) = lookup(DECOMP, c) {
            for d in decomposed.chars() {
                push_folded(d, &mut out);
            }
        } else {
            push_folded(c, &mut out);
        }
    }
    out
}

const S_BASE: u32 = 0xAC00;
const L_BASE: u32 = 0x1100;
const V_BASE: u32 = 0x1161;
const T_BASE: u32 = 0x11A7;
const T_COUNT: u32 = 28;
const N_COUNT: u32 = 21 * T_COUNT;
const S_COUNT: u32 = 19 * N_COUNT;

/// The comparison form of `caseInsensitiveCompare`: canonical decomposition (marks kept, Hangul included) and full
/// case folding of Basic Multilingual Plane letters. Foundation does not fold supplementary-plane letters
/// (`vectors/text/case-compare.json`, case `hand-56`: U+10400 against U+10428 is not equal).
fn comparison_key(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let push = |d: char, out: &mut String| {
        if d.is_ascii() {
            out.push(d.to_ascii_lowercase());
        } else if let Some(folding) = lookup(CASEFOLD, d) {
            out.push_str(folding);
        } else {
            out.push(d);
        }
    };
    for c in text.chars() {
        let value = c as u32;
        if c.is_ascii() {
            push(c, &mut out);
        } else if (S_BASE..S_BASE + S_COUNT).contains(&value) {
            let index = value - S_BASE;
            for part in [
                L_BASE + index / N_COUNT,
                V_BASE + (index % N_COUNT) / T_COUNT,
            ] {
                out.extend(char::from_u32(part));
            }
            if !index.is_multiple_of(T_COUNT) {
                out.extend(char::from_u32(T_BASE + index % T_COUNT));
            }
        } else if let Some(decomposed) = lookup(DECOMP, c) {
            for d in decomposed.chars() {
                push(d, &mut out);
            }
        } else {
            push(c, &mut out);
        }
    }
    out
}

/// `a.caseInsensitiveCompare(b) == .orderedSame`.
pub fn case_insensitive_eq(a: &str, b: &str) -> bool {
    comparison_key(a) == comparison_key(b)
}

// MARK: user-perceived characters

fn is_control(c: char) -> bool {
    c.is_control() || matches!(c, '\u{200B}' | '\u{2028}' | '\u{2029}' | '\u{FEFF}')
}

fn is_extend(c: char) -> bool {
    in_ranges(EXTEND, c)
        || matches!(
            c,
            '\u{200C}'
                | '\u{200D}'
                | '\u{FE00}'..='\u{FE0F}'
                | '\u{E0100}'..='\u{E01EF}'
                | '\u{1F3FB}'..='\u{1F3FF}'
                | '\u{E0020}'..='\u{E007F}'
                | '\u{FF9E}'..='\u{FF9F}'
        )
}

fn is_regional_indicator(c: char) -> bool {
    ('\u{1F1E6}'..='\u{1F1FF}').contains(&c)
}

