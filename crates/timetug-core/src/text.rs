#[derive(PartialEq, Clone, Copy)]
enum Hangul {
    L,
    V,
    T,
    Lv,
    Lvt,
    Other,
}

fn hangul(c: char) -> Hangul {
    match c {
        '\u{1100}'..='\u{115F}' | '\u{A960}'..='\u{A97C}' => Hangul::L,
        '\u{1160}'..='\u{11A7}' | '\u{D7B0}'..='\u{D7C6}' => Hangul::V,
        '\u{11A8}'..='\u{11FF}' | '\u{D7CB}'..='\u{D7FB}' => Hangul::T,
        '\u{AC00}'..='\u{D7A3}' => {
            if (c as u32 - S_BASE).is_multiple_of(T_COUNT) {
                Hangul::Lv
            } else {
                Hangul::Lvt
            }
        }
        _ => Hangul::Other,
    }
}

/// Whether there is no cluster boundary between `previous` (the last scalar of the cluster so far) and `c` (UAX #29,
/// extended grapheme clusters, without the Prepend rule). `pict` is the emoji-sequence state, `regional` the number of
/// regional indicators in the cluster so far.
fn joins(previous: char, c: char, pict: u8, regional: usize) -> bool {
    if previous == '\r' && c == '\n' {
        return true;
    }
    if is_control(previous) || is_control(c) {
        return false;
    }
    if is_extend(c) {
        return true;
    }
    if pict == 2 && is_pictographic(c) {
        return true;
    }
    if is_regional_indicator(previous) && is_regional_indicator(c) && regional % 2 == 1 {
        return true;
    }
    matches!(
        (hangul(previous), hangul(c)),
        (Hangul::L, Hangul::L | Hangul::V | Hangul::Lv | Hangul::Lvt)
            | (Hangul::V | Hangul::Lv, Hangul::V | Hangul::T)
            | (Hangul::Lvt | Hangul::T, Hangul::T)
    )
}

/// Swift's `Character`s of `text`: its extended grapheme clusters.
pub(crate) fn graphemes(text: &str) -> Vec<&str> {
    let mut clusters = Vec::new();
    let mut start = 0;
    let mut previous: Option<char> = None;
    let mut pict = 0u8; // 0: none, 1: ExtPict Extend*, 2: ExtPict Extend* ZWJ
    let mut regional = 0usize;
    for (index, c) in text.char_indices() {
        if let Some(p) = previous {
            if joins(p, c, pict, regional) {
                pict = match (pict, c) {
                    (1, '\u{200D}') => 2,
                    (1, _) if is_extend(c) => 1,
                    (2, _) if is_pictographic(c) => 1,
                    _ => 0,
                };
                if is_regional_indicator(c) {
                    regional += 1;
                }
                previous = Some(c);
                continue;
            }
            clusters.push(&text[start..index]);
            start = index;
        }
        pict = u8::from(is_pictographic(c));
        regional = usize::from(is_regional_indicator(c));
        previous = Some(c);
    }
    if previous.is_some() {
        clusters.push(&text[start..]);
    }
    clusters
}

/// Swift's `String.count`.
pub(crate) fn grapheme_count(text: &str) -> usize {
    graphemes(text).len()
}

/// Swift's `String(text.prefix(n))`.
pub(crate) fn prefix_graphemes(text: &str, n: usize) -> String {
    graphemes(text).into_iter().take(n).collect()
}

/// Swift's `Character.isLetter || isNumber`, decided by the first scalar (`Alphabetic`, or any numeric type).
pub(crate) fn is_letter_or_number(first_scalar: char) -> bool {
    first_scalar.is_alphabetic() || first_scalar.is_numeric()
}
