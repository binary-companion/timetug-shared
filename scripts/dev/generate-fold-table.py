#!/usr/bin/env python3
"""Generates crates/timetug-core/src/fold_table.rs, the data behind `text::fold` and `text::case_insensitive_eq`.

Usage: generate-fold-table.py [--check] [--vectors DIR]

The port needs Foundation's `folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil)` and
`caseInsensitiveCompare`. `std` has no Unicode decomposition and no full case folding, and no crate may be added, so the
data is generated here from Python's `unicodedata` (canonical decompositions, general category Mn) and `str.casefold()`
(full case folding), restricted to the Basic Multilingual Plane for case folding: Foundation's comparison does not fold
supplementary-plane letters (vectors/text/case-compare.json, case hand-56: U+10400 against U+10428 is not equal).
After generating, the script replays vectors/text/fold.json and vectors/text/case-compare.json against a Python model of
the Rust algorithm and exits 1 on any difference, so a table that disagrees with the Swift baseline is never written.

  DECOMP    every non-ASCII, non-Hangul character with a canonical decomposition -> its full decomposition
  CASEFOLD  every non-ASCII BMP character whose full case folding is not itself -> the folding
  MARKS     ranges of general category Mn (nonspacing marks), which diacritic-insensitive folding drops
  EXTEND    ranges of general category Mn, Mc and Me, which attach to the character before them in a grapheme cluster

--check regenerates in memory and fails if the committed file differs."""
import argparse
import json
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'crates/timetug-core/src/fold_table.rs'


def is_hangul(c):
    return 0xAC00 <= ord(c) <= 0xD7A3


def tables():
    decomp, casefold, marks, extend = [], [], [], []
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        d = unicodedata.normalize('NFD', c)
        if d != c and not is_hangul(c):
            decomp.append((c, d))
        if cp <= 0xFFFF:
            f = c.casefold()
            if f != c:
                casefold.append((c, f))
        category = unicodedata.category(c)
        for wanted, ranges in (('Mn', marks), ('Mn Mc Me', extend)):
            if category in wanted.split():
                if ranges and ranges[-1][1] == cp - 1:
                    ranges[-1] = (ranges[-1][0], cp)
                else:
                    ranges.append((cp, cp))
    return decomp, casefold, marks, extend


def lit(s):
    return '"' + ''.join('\\u{%X}' % ord(ch) for ch in s) + '"'


def render(decomp, casefold, marks, extend):
    out = ['// @generated by scripts/dev/generate-fold-table.py from Python unicodedata %s. Do not edit.' % unicodedata.unidata_version,
           '// Data for `text::fold` and `text::case_insensitive_eq` (see the generator for how it is derived and checked).',
           '', '/// Full canonical decompositions (Hangul syllables are handled by arithmetic), sorted by character.',
           'pub(crate) static DECOMP: &[(char, &str)] = &[']
    out += ["    ('\\u{%X}', %s)," % (ord(c), lit(d)) for c, d in decomp]
    out += ['];', '', '/// Full case foldings of BMP characters, sorted by character.',
            'pub(crate) static CASEFOLD: &[(char, &str)] = &[']
    out += ["    ('\\u{%X}', %s)," % (ord(c), lit(f)) for c, f in casefold]
    out += ['];', '', '/// Ranges (inclusive) of general category Mn, sorted.', 'pub(crate) static MARKS: &[(char, char)] = &[']
    out += ["    ('\\u{%X}', '\\u{%X}')," % (a, b) for a, b in marks]
    out += ['];', '', '/// Ranges (inclusive) of general category Mn, Mc and Me, sorted.', 'pub(crate) static EXTEND: &[(char, char)] = &[']
    out += ["    ('\\u{%X}', '\\u{%X}')," % (a, b) for a, b in extend]
    out += ['];', '']
    return '\n'.join(out)


def model(decomp, casefold, marks):
    dm, cm = dict(decomp), dict(casefold)

    def is_mn(c):
        return any(a <= ord(c) <= b for a, b in marks)

    def fold(text):
        out = []
        for c in text:
            if ord(c) < 0x80:
                out.append(c.lower())
                continue
            for d in dm.get(c, c):
                if is_mn(d):
                    continue
                for f in (d.lower() if ord(d) < 0x80 else cm.get(d, d)):
                    if not is_mn(f):
                        out.append(f)
        return ''.join(out)

    def nfd(text):
        out = []
        for c in text:
            out.append(unicodedata.normalize('NFD', c) if is_hangul(c) else dm.get(c, c))
        return ''.join(out)

    def key(text):
        out = []
        for c in text:
            for d in (c if ord(c) < 0x80 else nfd(c)):
                out.append(d.lower() if ord(d) < 0x80 else cm.get(d, d))
        return ''.join(out)

    return fold, key


def normalize(folded):
    return ' '.join(''.join(c if (c.isalpha() or c.isnumeric()) else ' ' for c in folded).split())


def verify(decomp, casefold, marks, vectors):
    fold, key = model(decomp, casefold, marks)
    bad = []
    for case in json.loads((vectors / 'text/fold.json').read_text())['cases']:
        if normalize(fold(case['input']['text'])) != case['expected']['result']:
            bad.append('fold ' + case['name'])
    for case in json.loads((vectors / 'text/case-compare.json').read_text())['cases']:
        if (key(case['input']['a']) == key(case['input']['b'])) != case['expected']['same']:
            bad.append('case-compare ' + case['name'])
    return bad


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--vectors', default=str(ROOT / 'vectors'))
    args = parser.parse_args()
    decomp, casefold, marks, extend = tables()
    bad = verify(decomp, casefold, marks, Path(args.vectors))
    if bad:
        print('the generated tables disagree with the Swift vectors:', *bad[:20], sep='\n  ')
        return 1
    text = render(decomp, casefold, marks, extend)
    if args.check:
        if OUT.read_text() != text:
            print('%s is out of date; run scripts/dev/generate-fold-table.py' % OUT.relative_to(ROOT))
            return 1
        return 0
    OUT.write_text(text)
    print('wrote %s (%d decompositions, %d foldings, %d mark ranges, %d extend ranges)' % (OUT.relative_to(ROOT), len(decomp), len(casefold), len(marks), len(extend)))
    return 0


sys.exit(main())
